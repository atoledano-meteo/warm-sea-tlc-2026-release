BLOCKS = [
    ('Morrison--YSU', '', ('clim', 'curr', 'plus2k')),
    ('Thompson--MYNN', 'tmynn_', ('clim', 'curr', 'plus2k')),
    ('Morrison--YSU', '', ('plus2kall',)),
]
SST = {'clim': 'CLIM', 'curr': 'CURR', 'plus2k': '+2K', 'plus2kall': '+2K-ALL'}


def block_rows(fmt, states=None):
    rows, prev = [], None
    for physics, prefix, ssts in BLOCKS:
        for mem in ('ctrl', 'skb1', 'skb2'):
            for sst in ssts:
                if states and sst not in states and sst != 'plus2kall':
                    continue
                block = (physics, sst == 'plus2kall')
                if prev is not None and block != prev:
                    rows.append(r'\hline')
                rows.append(
                    f"{physics if block != prev else ''} & {mem.upper()} & {SST[sst]} & "
                    + ' & '.join(fmt(f'{prefix}{sst}_{mem}'))
                    + r' \\'
                )
                prev = block
    return '\n'.join(rows)


def table_s2():
    a = pd.read_csv(DATASET / 'diagnostics/mcv_cyclone_summary.csv').set_index('run')
    P = pd.read_csv(DATASET / 'diagnostics/mcv_vertical_profiles.csv', parse_dates=['time'])
    z10 = P[(P.time >= '2026-10-03 22:00') & (P.time <= '2026-10-04 08:00')].groupby('run').z10.mean()
    fmt = lambda r: [f'{mean_rain(r):.1f}', f'{a.loc[r, "mcv_peak_f"]:.1f}', num(z10[r], 1)]
    return (
        r"""\begin{table}[htbp]
\caption{Rainfall and Mesoscale Convective Vortex in All Simulations}
\label{tab:mcv}
\centering\fontsize{8.5}{10.5}\selectfont\renewcommand{\arraystretch}{1.2}\setlength{\tabcolsep}{5pt}\vspace{3pt}
\begin{tabular}{lllccc}
\hline
 & & & Rain & \multicolumn{2}{c}{MCV} \\
Physics & Member & SST & $R$ (mm) & $\zeta_m$ ($f$) & $\zeta_{10\,\mathrm{m}}$ ($f$) \\
\hline
"""
        + block_rows(fmt)
        + r"""
\hline
\end{tabular}
\tablenote{$R$, 48 h mean rainfall over the verification region (observed 47.1~mm). $\zeta_m$, peak MCV vorticity; $\zeta_{10\,\mathrm{m}}$, vorticity at 10~m below the MCV, mean of 2200~UTC 3 to 0800~UTC 4 October (Text S2.1, Figure S3d).}
\end{table}
"""
    )


def table_s3():
    a = pd.read_csv(DATASET / 'diagnostics/mcv_cyclone_summary.csv').set_index('run')

    def fmt(r):
        q = a.loc[r]
        note = r'$^{a}$' if r == 'plus2k_skb1' else ''
        return [
            f'{-q.deficit_hPa:.1f}',
            f'{q.v10max_ms:.0f}',
            f'{q.marine_outputs:.0f}',
            f'{round(q.thermal_pct * q.marine_outputs / 100):.0f}',
            f'{q.coherent:.0f}{note}',
        ]

    return (
        r"""\begin{table}[htbp]
\caption{Surface Cyclone Associated With the MCV, Over the Sea}
\label{tab:cyclone}
\centering\fontsize{8.5}{10.5}\selectfont\renewcommand{\arraystretch}{1.2}\setlength{\tabcolsep}{5pt}\vspace{3pt}
\begin{tabular}{lllccccc}
\hline
Physics & Member & SST & \shortstack{Depth\\(hPa)} & \shortstack{$V_{10}$\\(m~s$^{-1}$)} & \shortstack{Over sea\\(h)} & \shortstack{Warm core\\(h)} & \shortstack{Tropical-like\\(h)} \\
\hline
"""
        + block_rows(fmt, states=('curr', 'plus2k'))
        + r"""
\hline
\end{tabular}
\tablenote{In CLIM, only two members have an associated surface cyclone, less than 2~hPa deep and without a warm core (not shown). Depth, largest depth $\Delta p$ of the cyclone; $V_{10}$, maximum 10 m wind (both Text S2.2). Over sea, hourly outputs with the center over the sea; Warm core and Tropical-like, those meeting the thermal criteria (Text S2.3) and the tropical-like criteria (Text S2.4). $^{a}$Eye-like feature; 15 consecutive hourly outputs; still over the sea when the run ends (0000~UTC 5 October).}
\end{table}
"""
    )


