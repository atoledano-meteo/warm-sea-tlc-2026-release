def num(x, d=1, sign=False):
    """Number with a true minus sign, and an explicit plus sign when sign=True."""
    if pd.isna(x):
        return '--'
    t = f'{abs(x):.{d}f}'
    return f'$-{t}$' if x < 0 and t.strip('0.') else (f'$+{t}$' if sign and t.strip('0.') else t)


def mean_rain(run):
    """48 h mean rainfall over the verification region, after regridding to the verification grid."""
    W = load_npz(DATASET / 'regrid_model_to_verification.npz')
    with xr.open_dataset(DATASET / 'rainfall' / f'{run}.nc') as d:
        tot = W @ d.rain.values.sum(0).astype('f8').ravel()
    with xr.open_dataset(DATASET / 'verification_region.nc') as v:
        mask = v.mask.values.ravel() > 0
    tot = tot / np.maximum(np.asarray(W.sum(1)).ravel(), 1e-12)
    return tot[mask].mean()


